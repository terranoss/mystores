<?php

namespace App\Services;

use App\Models\Order;
use Dompdf\Dompdf;
use Dompdf\Options;

class PackingListPdfService
{
    /**
     * Build an A4 packing-list PDF from a local order and its items.
     */
    public function generate(Order $order): string
    {
        $order->loadMissing(['items', 'store:id,shop_name,shop_id,region']);

        $html = $this->renderHtml($order);

        $options = new Options();
        $options->set('isRemoteEnabled', false);
        $options->set('defaultFont', 'DejaVu Sans');

        $dompdf = new Dompdf($options);
        $dompdf->loadHtml($html);
        $dompdf->setPaper('A4', 'portrait');
        $dompdf->render();

        $pdf = $dompdf->output(['compress' => 0]);
        if ($pdf === null || $pdf === '') {
            throw new \RuntimeException('Failed to generate packing list PDF.');
        }

        return $pdf;
    }

    private function renderHtml(Order $order): string
    {
        $storeName = e($order->store?->shop_name ?? 'Store');
        $orderSn = e($order->order_sn);
        $buyer = e($order->buyer_username ?? '—');
        $currency = e($order->currency ?? 'MYR');
        $orderedAt = $order->ordered_at
            ? e($order->ordered_at->timezone(config('app.timezone'))->format('Y-m-d H:i'))
            : '—';
        $status = e($order->order_status ?? '');
        $total = number_format((float) $order->total_amount, 2);

        $rows = '';
        $lineNo = 1;
        foreach ($order->items as $item) {
            $name = e($item->item_name ?? 'Item');
            $qty = (int) $item->quantity;
            $price = number_format((float) $item->price, 2);
            $lineTotal = number_format((float) $item->price * $qty, 2);
            $sku = e($item->sku ?: ($item->model_id ? (string) $item->model_id : (string) $item->item_id));
            $rows .= "<tr>
                <td class=\"c item-meta\">{$lineNo}</td>
                <td class=\"item-meta\">{$sku}</td>
                <td class=\"item-name\">{$name}</td>
                <td class=\"c item-qty\">{$qty}</td>
                <td class=\"r item-meta\">{$price}</td>
                <td class=\"r item-meta\">{$lineTotal}</td>
            </tr>";
            $lineNo++;
        }

        if ($rows === '') {
            $rows = '<tr><td colspan="6" class="c">No items</td></tr>';
        }

        return <<<HTML
<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<style>
  body { font-family: DejaVu Sans, sans-serif; font-size: 11px; color: #111; margin: 28px; }
  h1 { font-size: 18px; margin: 0 0 4px; }
  .sub { color: #555; margin-bottom: 18px; }
  .meta { width: 100%; margin-bottom: 16px; border-collapse: collapse; }
  .meta td { padding: 3px 8px 3px 0; vertical-align: top; }
  .meta .label { color: #666; width: 110px; }
  table.items { width: 100%; border-collapse: collapse; margin-top: 8px; }
  table.items th, table.items td { border: 1px solid #ccc; padding: 10px 8px; }
  table.items th { background: #f3f3f3; text-align: left; font-size: 11px; text-transform: uppercase; }
  table.items td.item-name { font-size: 16px; font-weight: bold; }
  table.items td.item-qty { font-size: 18px; font-weight: bold; }
  table.items td.item-meta { font-size: 13px; }
  .c { text-align: center; }
  .r { text-align: right; }
  .total { margin-top: 14px; text-align: right; font-size: 13px; font-weight: bold; }
  .footer { margin-top: 28px; color: #888; font-size: 9px; }
</style>
</head>
<body>
  <h1>Packing List</h1>
  <div class="sub">MelurCom · {$storeName}</div>
  <table class="meta">
    <tr><td class="label">Order SN</td><td><strong>{$orderSn}</strong></td></tr>
    <tr><td class="label">Buyer</td><td>{$buyer}</td></tr>
    <tr><td class="label">Ordered at</td><td>{$orderedAt}</td></tr>
    <tr><td class="label">Status</td><td>{$status}</td></tr>
  </table>
  <table class="items">
    <thead>
      <tr>
        <th class="c" style="width:36px">#</th>
        <th style="width:90px">SKU / ID</th>
        <th>Item</th>
        <th class="c" style="width:48px">Qty</th>
        <th class="r" style="width:80px">Price</th>
        <th class="r" style="width:90px">Line total</th>
      </tr>
    </thead>
    <tbody>
      {$rows}
    </tbody>
  </table>
  <div class="total">Order total: {$currency} {$total}</div>
  <div class="footer">Generated by MelurCom for packing reference. Air waybill is provided by the marketplace.</div>
</body>
</html>
HTML;
    }
}
